/**
 * Genera un referto PDF del decorso clinico di un singolo paziente, con foto progressive
 * raggruppate per sede di ferita. Usa android.graphics.pdf.PdfDocument (zero dipendenze,
 * zero rete). Mostra SOLO punteggi grezzi e documentazione: nessuna interpretazione (MDR).
 * Multilingua: il parametro [lang] (lingua corrente dell'app) seleziona IT/EN/FR/ES.
 */
object PatientReportPdf {

    private const val PAGE_W = 595   // A4 @72dpi
    private const val PAGE_H = 842
    private const val MARGIN = 42f
    private const val CONTENT_W = PAGE_W - 2 * MARGIN
    private const val MAX_PHOTOS_PER_EVENT = 4

    // Palette
    private val ACCENT = 0xFF1A237E.toInt()        // indaco
    private val ACCENT_SOFT = 0xFFE8EAF6.toInt()   // indaco chiarissimo (righe alternate / chip)
    private val PANEL_BG = 0xFFF5F6FA.toInt()
    private val BORDER = 0xFFD3D7E0.toInt()
    private val TEXT_DARK = 0xFF243042.toInt()
    private val TEXT_GRAY = 0xFF6B7280.toInt()
    private val WHITE = Color.WHITE

    private val dateFmt = SimpleDateFormat("dd/MM/yyyy HH:mm", Locale.getDefault())
    private val dateOnly = SimpleDateFormat("dd/MM/yyyy", Locale.getDefault())

    suspend fun generate(context: Context, db: AppDatabase, patientId: Long, lang: AppLanguage): File {
        val dao = db.backupDao()
        val patient = dao.getAllPatients().firstOrNull { it.id == patientId }
            ?: throw IllegalArgumentException("Patient not found / Paziente non trovato")
        val wounds = dao.getAllWounds().filter { it.patientId == patientId }.sortedBy { it.createdAt }
        val woundIds = wounds.map { it.id }.toSet()
        val dressings = dao.getAllDressings().filter { it.assessmentId in woundIds }
        // Foto multiple per evento (tabella dressing_photos, position 0 = copertina),
        // ordinate per position; fallback alla sola photoUri dell'evento se assenti.
        val eventIds = dressings.map { it.id }.toSet()
        val photosByEvent = dao.getAllDressingPhotos()
            .filter { it.eventId in eventIds }
            .groupBy { it.eventId }
            .mapValues { (_, list) -> list.sortedBy { it.position }.map { it.photoUri } }
        val norton = dao.getAllNorton().filter { it.patientId == patientId }.sortedBy { it.createdAt }
        val nrs2002 = dao.getAllNRS2002().filter { it.patientId == patientId }.sortedBy { it.createdAt }
        val painNrs = dao.getAllPainNrs().filter { it.patientId == patientId }.sortedBy { it.createdAt }

        val doc = PdfDocument()
        try {
            val fullName = "${patient.surname} ${patient.name}".trim()
            val r = Renderer(doc, lang, fullName)

            r.headerBand(
                loc4(lang,
                    it = "REPORT DI DOCUMENTAZIONE — LESIONI",
                    en = "DOCUMENTATION REPORT — WOUNDS",
                    fr = "RAPPORT DE DOCUMENTATION — PLAIES",
                    es = "INFORME DE DOCUMENTACIÓN — HERIDAS"),
                loc4(lang,
                    it = "Solo documentazione clinica · non è un dispositivo medico",
                    en = "Clinical documentation only · not a medical device",
                    fr = "Documentation clinique uniquement · pas un dispositif médical",
                    es = "Solo documentación clínica · no es un producto sanitario")
            )

            r.disclaimer(loc4(lang,
                it = "Documento di sola documentazione clinica generato dall'applicazione. NON è un dispositivo medico: non fornisce diagnosi, raccomandazioni terapeutiche o supporto decisionale. Contiene dati personali sensibili: trattare secondo la normativa applicabile sulla protezione dei dati.",
                en = "Documentation-only report generated by the application. It is NOT a medical device: it does not provide diagnosis, therapeutic recommendations or decision support. Contains sensitive personal data: handle according to the applicable data protection law.",
                fr = "Document de documentation clinique uniquement, généré par l'application. Ce N'EST PAS un dispositif médical : il ne fournit ni diagnostic, ni recommandations thérapeutiques, ni aide à la décision. Contient des données personnelles sensibles : traiter conformément à la législation applicable sur la protection des données.",
                es = "Documento de documentación clínica únicamente, generado por la aplicación. NO es un producto sanitario: no proporciona diagnóstico, recomendaciones terapéuticas ni apoyo a la decisión. Contiene datos personales sensibles: tratar conforme a la legislación aplicable sobre protección de datos."))

            // ── Riquadro paziente ──
            val info = mutableListOf<Pair<String, String>>()
            info += loc4(lang, it = "Cognome e nome", en = "Surname and name", fr = "Nom et prénom", es = "Apellido y nombre") to fullName
            if (patient.fiscalCode.isNotBlank())
                info += loc4(lang, it = "Codice fiscale", en = "Fiscal code", fr = "Code fiscal", es = "Código fiscal") to patient.fiscalCode
            if (patient.birthDate.isNotBlank())
                info += loc4(lang, it = "Data di nascita", en = "Date of birth", fr = "Date de naissance", es = "Fecha de nacimiento") to patient.birthDate
            val wardBed = listOf(patient.ward, patient.bed).filter { it.isNotBlank() }.joinToString(" - ")
            if (wardBed.isNotBlank())
                info += loc4(lang, it = "Reparto / Letto", en = "Ward / Bed", fr = "Service / Lit", es = "Unidad / Cama") to wardBed
            info += loc4(lang, it = "Documento generato il", en = "Report generated on", fr = "Document généré le", es = "Documento generado el") to dateFmt.format(Date(System.currentTimeMillis()))
            r.panel(loc4(lang, it = "PAZIENTE", en = "PATIENT", fr = "PATIENT", es = "PACIENTE"), info)

            // ── Scale cliniche (solo punteggi grezzi) ──
            r.section(loc4(lang, it = "Scale cliniche (punteggi)", en = "Clinical scales (scores)", fr = "Échelles cliniques (scores)", es = "Escalas clínicas (puntuaciones)"))
            // I nomi/descrittori validati delle scale restano in origine inglese per FR/ES (fr = en, es = en).
            r.scaleTableBegin(loc4(lang, it = "Scala", en = "Scale", fr = "Échelle", es = "Escala"),
                loc4(lang, it = "Rilevazioni (data = punteggio)", en = "Readings (date = score)", fr = "Relevés (date = score)", es = "Mediciones (fecha = puntuación)"))
            r.scaleRow(loc4(lang, it = "Norton - rischio lesioni da pressione", en = "Norton - pressure injury risk", fr = "Norton - pressure injury risk", es = "Norton - pressure injury risk"), norton.map { it.createdAt to "${it.totalScore}/20" })
            r.scaleRow(loc4(lang, it = "NRS-2002 - screening finale", en = "NRS-2002 - final screening", fr = "NRS-2002 - dépistage final", es = "NRS-2002 - cribado final"), nrs2002.map { it.createdAt to "${it.totalScore}/7" })
            r.scaleRow(loc4(lang, it = "Dolore (NRS)", en = "Pain (NRS)", fr = "Douleur (NRS)", es = "Dolor (NRS)"), painNrs.map { it.createdAt to "${it.painScore}/10" })
            r.scaleTableEnd()

            // ── Decorso per sede di ferita ──
            r.section(loc4(lang, it = "Decorso delle lesioni", en = "Wound course", fr = "Évolution des plaies", es = "Evolución de las heridas"))
            if (wounds.isEmpty()) {
                r.body(loc4(lang, it = "Nessuna lesione registrata.", en = "No wounds registered.", fr = "Aucune plaie enregistrée.", es = "Ninguna herida registrada."))
            }
            for (w in wounds) {
                val locLabel = locationLabel(w.location, lang)
                val titleW = if (w.name.isNotBlank()) "$locLabel — ${w.name}" else locLabel
                val specs = mutableListOf<Pair<String, String>>()
                if (w.type.isNotBlank()) {
                    // Per "ALTRO" aggiunge la descrizione libera inserita dall'utente (typeOther).
                    val typeText = typeLabel(w.type, lang) +
                        if (w.type == "ALTRO" && w.typeOther.isNotBlank()) ": ${w.typeOther}" else ""
                    specs += loc4(lang, it = "Tipo", en = "Type", fr = "Type", es = "Tipo") to typeText
                }
                if (w.origin.isNotBlank()) specs += loc4(lang, it = "Origine", en = "Origin", fr = "Origine", es = "Origen") to originLabel(w.origin, lang)
                // Profondità: mostrata in mm quando è sotto il centimetro (uso clinico comune).
                val depthStr = if (w.depthCm > 0f && w.depthCm < 1f) "%.0f mm".format(w.depthCm * 10)
                    else "%.1f cm".format(w.depthCm)
                specs += loc4(lang, it = "Misure iniziali (alla presa in carico)", en = "Initial size (at intake)", fr = "Mesures initiales (à la prise en charge)", es = "Medidas iniciales (al ingreso)") to
                    "%.1f × %.1f cm · %s %s  (%s %.1f cm²)".format(w.lengthCm, w.widthCm,
                        loc4(lang, it = "prof.", en = "depth", fr = "prof.", es = "prof."), depthStr,
                        loc4(lang, it = "L×W stima", en = "L×W estimate", fr = "L×l estimation", es = "L×A estimación"), w.areaCm2)
                r.woundHeader(titleW, specs)

                val wd = dressings.filter { it.assessmentId == w.id }.sortedBy { it.createdAt }
                val n = wd.size

                // Riga cronologica di sintesi: prima/ultima rilevazione + numero medicazioni
                if (n > 0) {
                    r.body(loc4(lang,
                        it = "Prima rilevazione: ${dateOnly.format(Date(wd.first().createdAt))} — Ultima: ${dateOnly.format(Date(wd.last().createdAt))} — $n medicazioni documentate",
                        en = "First record: ${dateOnly.format(Date(wd.first().createdAt))} — Last: ${dateOnly.format(Date(wd.last().createdAt))} — $n dressings documented",
                        fr = "Premier relevé : ${dateOnly.format(Date(wd.first().createdAt))} — Dernier : ${dateOnly.format(Date(wd.last().createdAt))} — $n pansements documentés",
                        es = "Primer registro: ${dateOnly.format(Date(wd.first().createdAt))} — Último: ${dateOnly.format(Date(wd.last().createdAt))} — $n curaciones documentadas"))
                }
                if (w.notes.isNotBlank()) {
                    r.body(loc4(lang, it = "Note: ", en = "Notes: ", fr = "Notes : ", es = "Notas: ") + w.notes)
                }

                // Andamento temporale: tabella cronologica + grafico tessuti (solo dati, zero interpretazione)
                if (n > 0) {
                    r.chronoTable(lang, wd)
                }
                if (n >= 2) {
                    r.tissueChart(lang, wd)
                }

                r.subLabel(
                    if (n == 0)
                        loc4(lang, it = "Decorso: nessuna medicazione registrata", en = "Course: no dressings recorded", fr = "Évolution : aucun pansement enregistré", es = "Evolución: ninguna curación registrada")
                    else
                        loc4(lang, it = "Sequenza fotografica ($n medicazioni)", en = "Photo sequence ($n dressings)", fr = "Séquence photographique ($n pansements)", es = "Secuencia fotográfica ($n curaciones)")
                )
                for ((idx, d) in wd.withIndex()) {
                    val uris = (photosByEvent[d.id] ?: listOf(d.photoUri))
                        .filter { it.isNotBlank() }
                        .take(MAX_PHOTOS_PER_EVENT)
                    r.dressing(context, idx + 1, d, uris)
                }
            }

            r.finish()

            val exportDir = File(context.cacheDir, "exports").apply { mkdirs() }
            // Nome file SENZA PII: prefisso + iniziali + data + id (il nome completo è dentro al PDF).
            val prefix = "report"
            val initials = "${patient.surname.firstOrNull()?.uppercaseChar() ?: 'X'}${patient.name.firstOrNull()?.uppercaseChar() ?: 'X'}"
            val date = java.text.SimpleDateFormat("yyyyMMdd", java.util.Locale.US).format(java.util.Date())
            val name = "${prefix}_${initials}_${date}_$patientId"
                .replace(Regex("[^A-Za-z0-9_]"), "_").take(48)
            val file = File(exportDir, "$name.pdf")
            FileOutputStream(file).use { doc.writeTo(it) }
            return file
        } finally {
            runCatching { doc.close() }
            PhotoManager.clearCache() // libera la cache thumbnail riempita per il referto
        }
    }

    // Mappa i codici enum salvati nel DB all'etichetta nella lingua scelta (fallback: codice leggibile).
    // Gli enum espongono label nelle 4 lingue (IT/EN/FR/ES) tramite label(lang).
    private fun typeLabel(code: String, lang: AppLanguage) =
        runCatching { WoundType.valueOf(code) }.getOrNull()?.label(lang)
            ?: code.replace("_", " ")
    private fun originLabel(code: String, lang: AppLanguage) =
        runCatching { WoundOrigin.valueOf(code) }.getOrNull()?.label(lang)
            ?: code.replace("_", " ")
    private fun exudateLabel(code: String, lang: AppLanguage) =
        runCatching { ExudateLevel.valueOf(code) }.getOrNull()?.label(lang)
            ?: code.replace("_", " ")
    private fun locationLabel(code: String, lang: AppLanguage) =
        runCatching { WoundLocation.valueOf(code) }.getOrNull()?.label(lang)
            ?: runCatching { com.example.woundmanagement.ui.components.BodyZone.valueOf(code) }.getOrNull()?.label(lang)
            ?: code.replace("_", " ")

    /**
     * Medicazione in chiaro: record nuovi = enum primaria/secondaria localizzati
     * (per "Altro" il testo libero è in dressingType); record legacy = testo composto.
     * "Nessuna" non entra mai nella composizione "X + Y"; compare da sola solo se
     * non è stata applicata alcuna medicazione.
     */
    internal fun dressingText(d: DressingEventEntity, lang: AppLanguage): String {
        // Record nuovi: campo strutturato; "ALTRO:testo" porta il testo libero DENTRO il
        // campo (mai concatenato in dressingType: attribuzione sempre non ambigua).
        fun resolvePrimary(raw: String): String? = when {
            raw.startsWith("ALTRO:") -> raw.removePrefix("ALTRO:")
            else -> runCatching { com.example.woundmanagement.domain.model.PrimaryDressing.valueOf(raw) }.getOrNull()
                ?.takeIf { it != com.example.woundmanagement.domain.model.PrimaryDressing.NON_SPECIFICATA &&
                    it != com.example.woundmanagement.domain.model.PrimaryDressing.NESSUNA }?.label(lang)
        }
        fun resolveSecondary(raw: String): String? = when {
            raw.startsWith("ALTRO:") -> raw.removePrefix("ALTRO:")
            else -> runCatching { com.example.woundmanagement.domain.model.SecondaryDressing.valueOf(raw) }.getOrNull()
                ?.takeIf { it != com.example.woundmanagement.domain.model.SecondaryDressing.NON_SPECIFICATA &&
                    it != com.example.woundmanagement.domain.model.SecondaryDressing.NESSUNA }?.label(lang)
        }
        if (d.primaryDressing.isBlank() && d.secondaryDressing.isBlank()) return d.dressingType // legacy
        val parts = listOfNotNull(resolvePrimary(d.primaryDressing), resolveSecondary(d.secondaryDressing))
        if (parts.isEmpty() &&
            (d.primaryDressing == com.example.woundmanagement.domain.model.PrimaryDressing.NESSUNA.name ||
             d.secondaryDressing == com.example.woundmanagement.domain.model.SecondaryDressing.NESSUNA.name))
            return com.example.woundmanagement.domain.model.PrimaryDressing.NESSUNA.label(lang)
        return parts.joinToString(" + ")
    }

    /** Essudato in chiaro: quantità + tipo (se specificato). */
    private fun exudateText(d: DressingEventEntity, lang: AppLanguage): String {
        val level = exudateLabel(d.exudateLevel, lang).ifBlank { "—" }
        val type = runCatching { com.example.woundmanagement.domain.model.ExudateType.valueOf(d.exudateType) }.getOrNull()
        return if (type != null && type != com.example.woundmanagement.domain.model.ExudateType.NON_SPECIFICATO)
            "$level · ${type.label(lang)}" else level
    }

    // ── Renderer con paginazione, intestazioni e cursore verticale ──
    private class Renderer(val doc: PdfDocument, val lang: AppLanguage, val patientName: String) {
        private var pageNum = 1
        private var page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNum).create())
        private var canvas: Canvas = page.canvas
        private var y = MARGIN
        private val bottomLimit = PAGE_H - MARGIN - 18f

        private val titlePaint = Paint().apply { color = WHITE; textSize = 15f; isFakeBoldText = true; isAntiAlias = true }
        private val bandSubPaint = Paint().apply { color = 0xFFC5CAE9.toInt(); textSize = 9f; isAntiAlias = true }
        private val sectionPaint = Paint().apply { color = ACCENT; textSize = 13f; isFakeBoldText = true; isAntiAlias = true }
        private val panelTitlePaint = Paint().apply { color = ACCENT; textSize = 9.5f; isFakeBoldText = true; isAntiAlias = true; letterSpacing = 0.05f }
        private val labelPaint = TextPaint().apply { color = TEXT_GRAY; textSize = 9.5f; isFakeBoldText = true; isAntiAlias = true }
        private val valuePaint = TextPaint().apply { color = TEXT_DARK; textSize = 10f; isAntiAlias = true }
        private val bodyPaint = TextPaint().apply { color = TEXT_DARK; textSize = 10f; isAntiAlias = true }
        private val subLabelPaint = TextPaint().apply { color = ACCENT; textSize = 10f; isFakeBoldText = true; isAntiAlias = true }
        private val captionPaint = TextPaint().apply { color = TEXT_GRAY; textSize = 8f; isAntiAlias = true }
        private val smallPaint = TextPaint().apply { color = TEXT_GRAY; textSize = 8.5f; isAntiAlias = true }
        private val tableHeadPaint = Paint().apply { color = WHITE; textSize = 9f; isFakeBoldText = true; isAntiAlias = true }
        private val footerPaint = Paint().apply { color = TEXT_GRAY; textSize = 8f; isAntiAlias = true }

        private val accentFill = Paint().apply { color = ACCENT; isAntiAlias = true }
        private val accentSoftFill = Paint().apply { color = ACCENT_SOFT; isAntiAlias = true }
        private val panelFill = Paint().apply { color = PANEL_BG; isAntiAlias = true }
        private val whiteFill = Paint().apply { color = WHITE; isAntiAlias = true }
        private val borderStroke = Paint().apply { color = BORDER; style = Paint.Style.STROKE; strokeWidth = 0.9f; isAntiAlias = true }

        // ── intestazioni di pagina ──
        fun headerBand(title: String, subtitle: String) {
            // pagina 1: banda colorata a tutta larghezza
            canvas.drawRect(0f, 0f, PAGE_W.toFloat(), 84f, accentFill)
            canvas.drawText(title, MARGIN, 36f, titlePaint)
            canvas.drawText(subtitle, MARGIN, 56f, bandSubPaint)
            y = 84f + 16f
        }

        private fun runningHeader() {
            canvas.drawText(patientName, MARGIN, 26f, footerPaint)
            val right = loc4(lang, it = "Report lesioni", en = "Wound report", fr = "Rapport plaies", es = "Informe heridas")
            val tw = footerPaint.measureText(right)
            canvas.drawText(right, PAGE_W - MARGIN - tw, 26f, footerPaint)
            canvas.drawLine(MARGIN, 32f, PAGE_W - MARGIN, 32f, borderStroke)
            y = 44f
        }

        private fun footer() {
            canvas.drawLine(MARGIN, PAGE_H - 30f, PAGE_W - MARGIN, PAGE_H - 30f, borderStroke)
            val label = loc4(lang, it = "Pag. $pageNum", en = "Page $pageNum", fr = "Page $pageNum", es = "Pág. $pageNum")
            val tw = footerPaint.measureText(label)
            canvas.drawText(label, PAGE_W - MARGIN - tw, PAGE_H - 18f, footerPaint)
        }

        private fun newPage() {
            footer()
            doc.finishPage(page)
            pageNum++
            page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNum).create())
            canvas = page.canvas
            runningHeader()
        }

        private fun ensure(space: Float) {
            if (y + space > bottomLimit) newPage()
        }

        // ── disclaimer ──
        fun disclaimer(s: String) {
            para(s, smallPaint)
            y += 6f
        }

        // ── sezione con barra accento + titolo + filetto ──
        fun section(title: String) {
            ensure(30f)
            y += 8f
            canvas.drawRect(MARGIN, y - 2f, MARGIN + 4f, y + 12f, accentFill)
            canvas.drawText(title, MARGIN + 12f, y + 10f, sectionPaint)
            y += 18f
            canvas.drawLine(MARGIN, y, PAGE_W - MARGIN, y, borderStroke)
            y += 8f
        }

        // ── riquadro paziente ──
        fun panel(title: String, rows: List<Pair<String, String>>) {
            val pad = 12f
            val rowH = 16f
            val labelW = 150f
            val valueW = CONTENT_W - 2 * pad - labelW
            // misura altezza: titolo + righe (con eventuale wrap dei valori)
            var inner = 18f
            val layouts = rows.map { (_, v) ->
                StaticLayout.Builder.obtain(v, 0, v.length, valuePaint, valueW.toInt()).build()
            }
            layouts.forEach { inner += maxOf(rowH, it.height.toFloat()) }
            val boxH = inner + pad
            ensure(boxH + 6f)
            val top = y
            val rect = RectF(MARGIN, top, PAGE_W - MARGIN, top + boxH)
            canvas.drawRoundRect(rect, 8f, 8f, panelFill)
            canvas.drawRoundRect(rect, 8f, 8f, borderStroke)
            var yy = top + pad + 8f
            canvas.drawText(title, MARGIN + pad, yy, panelTitlePaint)
            yy += 14f
            rows.forEachIndexed { i, (k, _) ->
                canvas.drawText(k, MARGIN + pad, yy + 9f, labelPaint)
                canvas.save()
                canvas.translate(MARGIN + pad + labelW, yy)
                layouts[i].draw(canvas)
                canvas.restore()
                yy += maxOf(rowH, layouts[i].height.toFloat())
            }
            y = top + boxH + 8f
        }

        // ── tabella scale ──
        private var tableValueX = MARGIN + 200f
        fun scaleTableBegin(colA: String, colB: String) {
            ensure(20f)
            val hRect = RectF(MARGIN, y, PAGE_W - MARGIN, y + 16f)
            canvas.drawRect(hRect, accentFill)
            canvas.drawText(colA, MARGIN + 8f, y + 11.5f, tableHeadPaint)
            canvas.drawText(colB, tableValueX + 6f, y + 11.5f, tableHeadPaint)
            y += 16f
        }

        private var tableRowOdd = false

        /**
         * Oltre questo numero di rilevazioni la riga della tabella diventerebbe più alta
         * di una pagina intera e la parte eccedente verrebbe TAGLIATA in silenzio (la
         * paginazione lavora per righe, non può spezzarne una). Si mostrano le più
         * recenti e si dichiara quante sono state omesse.
         */
        private val MAX_SCALE_ENTRIES = 40

        fun scaleRow(label: String, entries: List<Pair<Long, String>>) {
            tableRowOdd = !tableRowOdd
            val shown = entries.takeLast(MAX_SCALE_ENTRIES)
            val omitted = entries.size - shown.size
            val valueText = if (entries.isEmpty()) "—"
                else shown.joinToString("    ") { "${dateOnly.format(Date(it.first))} = ${it.second}" } +
                    if (omitted > 0) "    " + loc4(lang,
                        it = "(mostrate le ultime ${shown.size} di ${entries.size})",
                        en = "(showing the last ${shown.size} of ${entries.size})",
                        fr = "(affichage des ${shown.size} dernières sur ${entries.size})",
                        es = "(mostradas las últimas ${shown.size} de ${entries.size})") else ""
            val valueW = (PAGE_W - MARGIN - (tableValueX + 6f) - 8f).toInt()
            val nameW = (tableValueX - MARGIN - 16f).toInt()
            val nameLayout = StaticLayout.Builder.obtain(label, 0, label.length, valuePaint, nameW).build()
            val valLayout = StaticLayout.Builder.obtain(valueText, 0, valueText.length, smallPaint, valueW).build()
            val rowH = maxOf(nameLayout.height, valLayout.height).toFloat() + 8f
            ensure(rowH)
            if (tableRowOdd) canvas.drawRect(RectF(MARGIN, y, PAGE_W - MARGIN, y + rowH), accentSoftFill)
            canvas.save(); canvas.translate(MARGIN + 8f, y + 4f); nameLayout.draw(canvas); canvas.restore()
            canvas.save(); canvas.translate(tableValueX + 6f, y + 4f); valLayout.draw(canvas); canvas.restore()
            y += rowH
        }

        fun scaleTableEnd() {
            canvas.drawLine(MARGIN, y, PAGE_W - MARGIN, y, borderStroke)
            tableRowOdd = false
            y += 8f
        }

        // ── lesione: titolo + specifiche in chip ──
        fun woundHeader(title: String, specs: List<Pair<String, String>>) {
