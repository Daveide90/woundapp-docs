        // ── tabella cronologica delle medicazioni (ordine ASC, header ripetuto a cambio pagina) ──
        fun chronoTable(lang: AppLanguage, events: List<DressingEventEntity>) {
            val headers = listOf(
                loc4(lang, it = "Data", en = "Date", fr = "Date", es = "Fecha"),
                loc4(lang, it = "Necr%", en = "Necr%", fr = "Nécr%", es = "Necr%"),
                "Slough%",
                loc4(lang, it = "Gran%", en = "Gran%", fr = "Gran%", es = "Gran%"),
                loc4(lang, it = "Epit%", en = "Epit%", fr = "Épit%", es = "Epit%"),
                loc4(lang, it = "Essudato", en = "Exudate", fr = "Exsudat", es = "Exudado"),
                loc4(lang, it = "Dolore", en = "Pain", fr = "Douleur", es = "Dolor"),
                loc4(lang, it = "Misure", en = "Size", fr = "Mesures", es = "Medidas"),
                loc4(lang, it = "Medicazione", en = "Dressing", fr = "Pansement", es = "Apósito")
            )
            val widths = listOf(50f, 28f, 40f, 28f, 26f, 78f, 30f, 68f,
                CONTENT_W - 50f - 28f - 40f - 28f - 26f - 78f - 30f - 68f)
            // Misure compatte per la cella (evoluzione nel tempo); "—" se non rilevate.
            fun measureCell(d: DressingEventEntity): String {
                if (d.lengthCm <= 0f && d.widthCm <= 0f && d.depthCm <= 0f) return "—"
                val dep = when {
                    d.depthCm <= 0f -> ""
                    d.depthCm < 1f -> " ·%.0fmm".format(d.depthCm * 10)
                    else -> " ·%.1fcm".format(d.depthCm)
                }
                return "%.1f×%.1f".format(d.lengthCm, d.widthCm) + dep
            }
            val rowPaint = TextPaint().apply { color = TEXT_DARK; textSize = 9f; isAntiAlias = true }
            val headPaint = Paint().apply { color = WHITE; textSize = 8f; isFakeBoldText = true; isAntiAlias = true }

            fun drawHeader() {
                canvas.drawRect(RectF(MARGIN, y, PAGE_W - MARGIN, y + 14f), accentFill)
                var x = MARGIN
                headers.forEachIndexed { i, h ->
                    canvas.drawText(h, x + 3f, y + 10f, headPaint)
                    x += widths[i]
                }
                y += 14f
            }

            ensure(34f)
            drawHeader()
            var odd = false
            for (d in events) {
                val cells = listOf(
                    dateOnly.format(Date(d.createdAt)),
                    "%.0f".format(d.tissueBlackPercent),
                    "%.0f".format(d.tissueYellowPercent),
                    "%.0f".format(d.tissueRedPercent),
                    "%.0f".format(d.tissuePinkPercent),
                    exudateText(d, lang),
                    d.painNrs?.let { "$it/10" } ?: "—",
                    measureCell(d),
                    dressingText(d, lang).ifBlank { "—" }
                )
                val layouts = cells.mapIndexed { i, c ->
                    StaticLayout.Builder.obtain(c, 0, c.length, rowPaint, (widths[i] - 6f).toInt().coerceAtLeast(10)).build()
                }
                val rowH = layouts.maxOf { it.height }.toFloat() + 5f
                if (y + rowH > bottomLimit) { newPage(); drawHeader() }
                odd = !odd
                if (odd) canvas.drawRect(RectF(MARGIN, y, PAGE_W - MARGIN, y + rowH), accentSoftFill)
                var x = MARGIN
                layouts.forEachIndexed { i, l ->
                    canvas.save(); canvas.translate(x + 3f, y + 2.5f); l.draw(canvas); canvas.restore()
                    x += widths[i]
                }
                y += rowH
            }
            canvas.drawLine(MARGIN, y, PAGE_W - MARGIN, y, borderStroke)
            y += 10f
        }

        // ── grafico a barre impilate delle % tessuti per data (nessuna linea di tendenza) ──
        fun tissueChart(lang: AppLanguage, all: List<DressingEventEntity>) {
            val step = ((all.size + 11) / 12).coerceAtLeast(1)
            val events = all.filterIndexed { i, _ -> i % step == 0 }
            val chartH = 140f
            val axisPad = 22f
            val labelH = 12f
            val legendH = 14f
            val noteH = if (step > 1) 11f else 0f
            ensure(14f + chartH + labelH + legendH + noteH + 12f)

            canvas.drawText(
                loc4(lang, it = "Composizione tessuti per data (%)", en = "Tissue composition by date (%)",
                    fr = "Composition tissulaire par date (%)", es = "Composición tisular por fecha (%)"),
                MARGIN, y + 10f, labelPaint
            )
            y += 16f

            val left = MARGIN + axisPad
            val plotW = CONTENT_W - axisPad
            val top = y
            val gridPaint = Paint().apply { color = BORDER; strokeWidth = 0.6f; isAntiAlias = true }
            val axisPaint = TextPaint().apply { color = TEXT_GRAY; textSize = 7f; isAntiAlias = true }
            for (v in 0..100 step 25) {
                val gy = top + chartH * (1 - v / 100f)
                canvas.drawLine(left, gy, MARGIN + CONTENT_W, gy, gridPaint)
                canvas.drawText("$v", MARGIN + 2f, gy + 2.5f, axisPaint)
            }

            val cNec = Paint().apply { color = 0xFF424242.toInt(); isAntiAlias = true }
            val cSlo = Paint().apply { color = 0xFFFBC02D.toInt(); isAntiAlias = true }
            val cGra = Paint().apply { color = 0xFFE53935.toInt(); isAntiAlias = true }
            val cEpi = Paint().apply { color = 0xFFE91E8C.toInt(); isAntiAlias = true }
            val dayMonth = SimpleDateFormat("dd/MM", Locale.getDefault())
            val slot = plotW / events.size
            val barW = (slot * 0.55f).coerceAtMost(30f)
            events.forEachIndexed { i, d ->
                val cx = left + slot * i + slot / 2f
                var base = top + chartH
                fun seg(p: Float, paint: Paint) {
                    if (p <= 0f) return
                    val h = chartH * (p.coerceIn(0f, 100f) / 100f)
                    canvas.drawRect(cx - barW / 2f, base - h, cx + barW / 2f, base, paint)
                    base -= h
                }
                seg(d.tissueBlackPercent, cNec)
                seg(d.tissueYellowPercent, cSlo)
                seg(d.tissueRedPercent, cGra)
                seg(d.tissuePinkPercent, cEpi)
                val lbl = dayMonth.format(Date(d.createdAt))
                val tw = axisPaint.measureText(lbl)
                canvas.drawText(lbl, cx - tw / 2f, top + chartH + 9f, axisPaint)
            }
            y = top + chartH + labelH

            // legenda colori
            var lx = left
            listOf(
                cNec to loc4(lang, it = "Necrosi", en = "Necrosis", fr = "Nécrose", es = "Necrosis"),
                cSlo to "Slough",
                cGra to loc4(lang, it = "Granulazione", en = "Granulation", fr = "Granulation", es = "Granulación"),
                cEpi to loc4(lang, it = "Epitelizzazione", en = "Epithelialization", fr = "Épithélialisation", es = "Epitelización")
            ).forEach { (paint, label) ->
                canvas.drawRect(lx, y + 2f, lx + 7f, y + 9f, paint)
                canvas.drawText(label, lx + 10f, y + 9f, axisPaint)
                lx += 10f + axisPaint.measureText(label) + 14f
            }
            y += legendH
            if (step > 1) {
                canvas.drawText(
                    loc4(lang, it = "1 barra ogni $step rilevazioni", en = "1 bar every $step records",
                        fr = "1 barre toutes les $step mesures", es = "1 barra cada $step registros"),
                    left, y + 8f, axisPaint
                )
                y += noteH
            }
            y += 8f
        }

        // ── medicazione: prima foto (sx, con bordo + didascalia) + dati (dx);
        //    eventuali foto aggiuntive dello stesso evento (fino a 4 totali) in riga sotto,
        //    con suffissi (es. 3a, 3b) e stessa data dell'evento. ──
        fun dressing(context: Context, n: Int, d: DressingEventEntity, photoUris: List<String>) {
            // Foto compatte per averne ~4 per pagina.
            val photoW = 130f
            val gap = 14f
            val bmps = photoUris.mapNotNull { uri ->
                PhotoManager.loadThumbnail(context, uri, 600)?.takeIf { it.width > 0 && it.height > 0 }
            }
            val bmp = bmps.firstOrNull()
            var photoH = 0f
            if (bmp != null) {
                photoH = bmp.height * (photoW / bmp.width)
                if (photoH > 145f) photoH = 145f
            }
            val hasPhoto = photoH > 0f
            // Con più foto la numerazione diventa "3a", "3b", ...; con una sola resta "3".
            val multi = bmps.size > 1
            val dataX = if (hasPhoto) MARGIN + photoW + gap else MARGIN
            val dataW = (PAGE_W - MARGIN - dataX).toInt()

            // costruisci righe dati
            val header = loc4(lang, it = "Medicazione $n", en = "Dressing $n", fr = "Pansement $n", es = "Curación $n") +
                "  ·  " + dateFmt.format(Date(d.createdAt))
            val lines = mutableListOf<Pair<String, TextPaint>>()
            lines += header to subLabelPaint
            lines += (loc4(lang,
                it = "Tessuti: nero %.0f%% · giallo %.0f%% · rosso %.0f%% · rosa %.0f%%",
                en = "Tissues: black %.0f%% · yellow %.0f%% · red %.0f%% · pink %.0f%%",
                fr = "Tissus : noir %.0f%% · jaune %.0f%% · rouge %.0f%% · rose %.0f%%",
                es = "Tejidos: negro %.0f%% · amarillo %.0f%% · rojo %.0f%% · rosa %.0f%%")
                .format(d.tissueBlackPercent, d.tissueYellowPercent, d.tissueRedPercent, d.tissuePinkPercent)) to smallPaint
            if (d.exudateLevel.isNotBlank())
                lines += (loc4(lang, it = "Essudato: ", en = "Exudate: ", fr = "Exsudat : ", es = "Exudado: ") + exudateText(d, lang)) to smallPaint
            // Dolore: riga presente solo se rilevato (null = non rilevato durante la procedura)
            d.painNrs?.let { pain ->
                lines += (loc4(lang, it = "Dolore (NRS): ", en = "Pain (NRS): ", fr = "Douleur (NRS) : ", es = "Dolor (NRS): ") + "$pain/10") to smallPaint
            }
            val applied = dressingText(d, lang)
            if (applied.isNotBlank())
                lines += (loc4(lang, it = "Medicazione applicata: ", en = "Dressing applied: ", fr = "Pansement appliqué : ", es = "Apósito aplicado: ") + applied) to smallPaint
            if (d.notes.isNotBlank())
                lines += (loc4(lang, it = "Note: ", en = "Notes: ", fr = "Notes : ", es = "Notas: ") + d.notes) to smallPaint

            val layouts = lines.map { (s, p) -> StaticLayout.Builder.obtain(s, 0, s.length, p, dataW).build() }
            var dataH = 0f
            layouts.forEach { dataH += it.height + 3f }
            if (hasPhoto) dataH += 24f // didascalia numerata + mini-barra tessuti

            val blockH = maxOf(photoH + 26f, dataH) + 8f
            ensure(blockH)
            val top = y

            if (hasPhoto && bmp != null) {
                val rect = RectF(MARGIN, top, MARGIN + photoW, top + photoH)
                canvas.drawBitmap(bmp, null, rect, null)
                canvas.drawRect(rect, borderStroke)
                // Didascalia: progressivo (+ suffisso "a" se l'evento ha più foto) + data in evidenza
                val boldCaption = TextPaint().apply { color = TEXT_DARK; textSize = 8.5f; isFakeBoldText = true; isAntiAlias = true }
                val mainNum = if (multi) "${n}a" else "$n"
                canvas.drawText("$mainNum.  ${dateOnly.format(Date(d.createdAt))}", MARGIN, top + photoH + 11f, boldCaption)
                // Mini-barra orizzontale con le % tessuti dell'evento (60×6 pt)
                val barTotal = d.tissueBlackPercent + d.tissueYellowPercent + d.tissueRedPercent + d.tissuePinkPercent
                if (barTotal > 0f) {
                    val barW = 60f
                    val barH = 6f
                    val by = top + photoH + 15f
                    var bx = MARGIN
                    listOf(
                        d.tissueBlackPercent to 0xFF424242.toInt(),
                        d.tissueYellowPercent to 0xFFFBC02D.toInt(),
                        d.tissueRedPercent to 0xFFE53935.toInt(),
                        d.tissuePinkPercent to 0xFFE91E8C.toInt()
                    ).forEach { (pct, colorInt) ->
                        if (pct > 0f) {
                            val w2 = barW * (pct / barTotal)
                            canvas.drawRect(bx, by, bx + w2, by + barH, Paint().apply { color = colorInt; isAntiAlias = true })
                            bx += w2
                        }
                    }
                    canvas.drawRect(RectF(MARGIN, by, MARGIN + barW, by + barH), borderStroke)
                }
            }

            var yy = top
            layouts.forEach { l ->
                canvas.save(); canvas.translate(dataX, yy); l.draw(canvas); canvas.restore()
                yy += l.height + 3f
            }
            y = top + blockH

            // Foto aggiuntive dell'evento (2ª..4ª) su una riga sotto il blocco principale:
            // stessa estetica (bordo + didascalia "3b. data"); la mini-barra tessuti resta
            // SOLO sotto la prima foto. Blocco autonomo con ensure() → niente sovrapposizioni.
            val extras = if (multi) bmps.drop(1) else emptyList()
            if (extras.isNotEmpty()) {
                val heights = extras.map { b -> (b.height * (photoW / b.width)).coerceAtMost(145f) }
                val rowH = heights.max() + 16f // spazio didascalia
                ensure(rowH + 6f)
                val rowTop = y
                val extraCaption = TextPaint().apply { color = TEXT_DARK; textSize = 8.5f; isFakeBoldText = true; isAntiAlias = true }
                extras.forEachIndexed { i, b ->
                    val x = MARGIN + i * (photoW + gap)
                    val h = heights[i]
                    val rect = RectF(x, rowTop, x + photoW, rowTop + h)
                    canvas.drawBitmap(b, null, rect, null)
                    canvas.drawRect(rect, borderStroke)
                    canvas.drawText("$n${'b' + i}.  ${dateOnly.format(Date(d.createdAt))}", x, rowTop + h + 11f, extraCaption)
                }
                y = rowTop + rowH + 4f
            }

            canvas.drawLine(MARGIN, y - 4f, PAGE_W - MARGIN, y - 4f, borderStroke)
        }

        // ── paragrafo con paginazione robusta (gestisce blocchi più alti di una pagina) ──
        private fun para(s: String, paint: TextPaint) {
            if (s.isEmpty()) return
            val width = CONTENT_W.toInt()
            val layout = StaticLayout.Builder.obtain(s, 0, s.length, paint, width).build()

            if (layout.height <= bottomLimit - MARGIN) {
                if (y + layout.height > bottomLimit) ensure(layout.height.toFloat())
                canvas.save(); canvas.translate(MARGIN, y); layout.draw(canvas); canvas.restore()
                y += layout.height + 2f
                return
            }

            var line = 0
            val lineCount = layout.lineCount
            while (line < lineCount) {
                val firstLineH = layout.getLineBottom(line) - layout.getLineTop(line)
                if (y + firstLineH > bottomLimit) ensure(firstLineH.toFloat())
                val blockTop = layout.getLineTop(line)
                var end = line
                while (end < lineCount && y + (layout.getLineBottom(end) - blockTop) <= bottomLimit) end++
                if (end == line) end = line + 1
                val blockBottom = layout.getLineBottom(end - 1)
                val blockHeight = (blockBottom - blockTop).toFloat()
                canvas.save()
                canvas.translate(MARGIN, y - blockTop)
                canvas.clipRect(0f, blockTop.toFloat(), width.toFloat(), blockBottom.toFloat())
                layout.draw(canvas)
                canvas.restore()
                y += blockHeight
                line = end
                if (line < lineCount) newPage()
            }
            y += 2f
        }

        fun finish() { footer(); doc.finishPage(page) }
    }
